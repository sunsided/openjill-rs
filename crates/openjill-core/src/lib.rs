/// Set of logical input commands currently active (held) during one tick.
pub type ActiveInput = BTreeSet<InputCommand>;

/// One logical input action produced by the input layer and consumed by game logic.
#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Debug)]
pub enum InputCommand {
    /// Move Jill to the left.
    MoveLeft,
    /// Move Jill to the right.
    MoveRight,
    /// Trigger a jump.
    Jump,
    /// Look up or climb up while on a vine/tree cell.
    ///
    /// Mirrors the `isUp` keyboard query in the Java reference, which is
    /// distinct from `isJump`: the original DOS game maps the up-arrow key to
    /// climbing and head-up animations, while space and alt drive the jump
    /// action.  Player movement code uses [`InputCommand::Up`] for climb
    /// transitions and [`InputCommand::Jump`] for the jump impulse.
    Up,
    /// Trigger ducking.
    Duck,
    /// Throw the currently held inventory item.
    ThrowItem,
    /// Select the next inventory item.
    NextInventory,
    /// Select the previous inventory item.
    PrevInventory,
    /// Pause or open the in-game menu.
    Pause,
    /// Request quitting the current game session.
    Quit,
    /// Toggle the sound ("NOISE") control-panel option.
    ToggleNoise,
    /// Toggle the "TURTLE" slow-motion control-panel option.
    ToggleTurtle,
    /// Save the current game (control-panel "SAVE" option).
    Save,
    /// Restore a saved game (control-panel "RESTORE" option).
    Restore,
    /// Play the intro level from the title screen (the original `Ctrl+P`
    /// title-screen cheat). Produced only as a modifier chord and consumed only
    /// by the start menu.
    PlayIntro,
    /// Enter the level editor from the title screen (the original `Ctrl+E`
    /// title-screen cheat). Produced only as a modifier chord and consumed only
    /// by the start menu.
    EnterEditor,
}

