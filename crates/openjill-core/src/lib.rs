/// One expanded 256-entry VGA palette used for indexed-framebuffer presentation.
#[derive(Clone, Debug)]
pub struct Palette {
    /// Expanded 8-bit RGB entries indexed by framebuffer color index.
    entries: [[u8; 3]; 256],
}

impl Palette {
    /// Builds a palette from a fully expanded 256-entry RGB table.
    pub fn new(entries: [[u8; 3]; 256]) -> Self {
        Self { entries }
    }

    /// Returns the expanded 8-bit RGB entries indexed by framebuffer color index.
    pub fn entries(&self) -> &[[u8; 3]; 256] {
        &self.entries
    }

    /// Returns the Jill of the Jungle VGA palette derived from `jill_color_map.properties`.
    ///
    /// This is the game's actual 256-color palette. SHA tileset pixels are already expanded
    /// to indices into this table at parse time; use this palette for all rendering.
    pub fn jill_vga() -> Self {
        Self {
            entries: JILL_VGA_PALETTE,
        }
    }

    /// Builds a synthetic greyscale palette used as a diagnostic fallback.
    pub fn greyscale_fallback() -> Self {
        let mut entries = [[0_u8; 3]; 256];
        for (index, color) in entries.iter_mut().enumerate() {
            let value = index as u8;
            *color = [value, value, value];
        }
        Self { entries }
    }

    /// Returns one palette entry as opaque RGBA bytes.
    pub fn rgba(&self, index: u8) -> [u8; 4] {
        let [r, g, b] = self.entries[index as usize];
        [r, g, b, 255]
    }
}

impl Default for Palette {
    /// Returns the Jill VGA palette as the default.
    fn default() -> Self {
        Self::jill_vga()
    }
}

#[cfg(test)]
mod tests {
    use super::{JILL_VGA_PALETTE, Palette};

    /// Unit under test: `Palette::jill_vga` / `JILL_VGA_PALETTE`.
    ///
    /// Invariants asserted: index 0 is the transparent-black sentinel, the 16 EGA colors
    /// are at their expected positions, index 255 is white, and every entry is opaque.
    #[test]
    fn jill_vga_palette_has_correct_ega_colors() {
        let palette = Palette::jill_vga();
        assert_eq!(
            palette.rgba(0),
            [0x00, 0x00, 0x00, 255],
            "index 0 transparent black"
        );
        assert_eq!(
            palette.rgba(1),
            [0x00, 0x00, 0xA2, 255],
            "index 1 dark blue"
        );
        assert_eq!(palette.rgba(4), [0xA2, 0x00, 0x00, 255], "index 4 dark red");
        assert_eq!(palette.rgba(15), [0xF7, 0xF7, 0xF7, 255], "index 15 white");
        assert_eq!(
            palette.rgba(255),
            [0xF7, 0xF7, 0xF7, 255],
            "index 255 white"
        );
        assert_eq!(JILL_VGA_PALETTE.len(), 256);
    }

    /// Unit under test: `Palette::greyscale_fallback`.
    ///
    /// Preconditions: the fallback constructor is called directly.
    ///
    /// Invariants asserted: index 0 is black, intermediate indices map to deterministic
    /// greyscale values, index 255 is white, and every entry is opaque.
    #[test]
    fn greyscale_fallback_is_deterministic_and_opaque() {
        let palette = Palette::greyscale_fallback();
        assert_eq!(palette.rgba(0), [0, 0, 0, 255]);
        assert_eq!(palette.rgba(127), [127, 127, 127, 255]);
        assert_eq!(palette.rgba(255), [255, 255, 255, 255]);
    }
}
